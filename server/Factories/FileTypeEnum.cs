/// <summary>
/// Represents the types of files supported by the application.
/// </summary>
public enum FileType
{
    /// <summary>
    /// Represents a JSON file.
    /// </summary>
    Json,

    /// <summary>
    /// Represents an XML file.
    /// </summary>
    Xml,

    /// <summary>
    /// Represents a CSV file.
    /// </summary>
    Csv,

    /// <summary>
    /// Represents a Microsoft Word document file (.docx).
    /// </summary>
    Docx,

    /// <summary>
    /// Represents a PDF file.
    /// </summary>
    Pdf,

    /// <summary>
    /// Represents a plain text file.
    /// </summary>
    Txt,

    /// <summary>
    /// Represents a Microsoft Excel file (.xlsx).
    /// </summary>
    Xlsx,

    /// <summary>
    /// Represents a Microsoft Excel file (.xls).
    /// </summary>
    Xls,

    /// <summary>
    /// Represents a PNG image file.
    /// </summary>
    Png,

    /// <summary>
    /// Represents a JPEG image file.
    /// </summary>
    Jpeg,

    /// <summary>
    /// Represents a BMP image file.
    /// </summary>
    Bmp
}